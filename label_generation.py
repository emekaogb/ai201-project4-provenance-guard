def generate_appeal_endpoint(app):
    """
    Register the POST /api/appeals/submit endpoint with the Flask app.

    This function should be called after creating the Flask app to register
    the appeals endpoint.

    Args:
        app: The Flask application instance
    """

    @app.route("/api/appeals/submit", methods=["POST"])
    def submit_appeal():
        """
        Submit an appeal for a classification decision.

        POST /api/appeals/submit
        {
            "content_id": "submission-id",
            "creator_id": "user-id",
            "reasoning": "50-1000 characters explaining disagreement",
            "evidence": "optional-url"
        }

        Returns (200 OK):
        {
            "appeal_id": "unique-id",
            "content_id": "original-submission-id",
            "status": "under_review",
            "submitted_at": "ISO-8601-timestamp",
            "message": "Your appeal has been received and is under review."
        }

        Error responses:
        - 400: Invalid input (missing fields, reasoning length, invalid evidence URL)
        - 404: content_id not found in audit log
        - 409: Appeal already exists for this content_id
        """
        try:
            # Parse JSON
            data = request.get_json()
            if data is None:
                return jsonify({"error": "Request body must be valid JSON."}), 400

            # Validate input
            is_valid, error_msg = validate_appeal_input(data)
            if not is_valid:
                logger.warning(f"Invalid appeal input: {error_msg}")
                return jsonify({"error": error_msg}), 400

            content_id = data.get("content_id").strip()
            creator_id = data.get("creator_id").strip()
            reasoning = data.get("reasoning").strip()
            evidence = data.get("evidence")
            if evidence:
                evidence = evidence.strip()

            # Check if content_id exists in audit log
            submission = get_submission_by_id(content_id)
            if submission is None:
                logger.warning(f"Appeal submission failed: content_id '{content_id}' not found")
                return jsonify({"error": f"Submission with content_id '{content_id}' not found."}), 404

            # Check if appeal already exists for this content_id
            existing_appeals = submission.get("appeals", [])
            if len(existing_appeals) > 0:
                logger.warning(f"Appeal already exists for content_id '{content_id}'")
                return jsonify({
                    "error": "An appeal has already been submitted for this submission. "
                             "Multiple appeals per submission are not currently supported."
                }), 409

            # Generate unique appeal ID
            appeal_id = str(uuid.uuid4())
            timestamp = datetime.utcnow().isoformat() + "Z"

            # Log the appeal (this updates the audit log)
            try:
                log_appeal(
                    appeal_id=appeal_id,
                    content_id=content_id,
                    creator_id=creator_id,
                    reasoning=reasoning,
                    evidence=evidence if evidence else None,
                )
            except Exception as e:
                logger.error(f"Error logging appeal: {str(e)}")
                return jsonify({"error": "Internal server error while processing appeal."}), 500

            # Build response
            response = {
                "appeal_id": appeal_id,
                "content_id": content_id,
                "status": "under_review",
                "submitted_at": timestamp,
                "message": "Your appeal has been received and is under review.",
            }

            logger.info(
                f"Appeal {appeal_id} submitted for content {content_id} "
                f"by creator {creator_id}"
            )

            return jsonify(response), 200

        except Exception as e:
            logger.error(f"Unexpected error in /api/appeals/submit: {str(e)}")
            return jsonify({"error": "Internal server error."}), 500

    return app
