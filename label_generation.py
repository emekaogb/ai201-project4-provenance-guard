# Appeal Validation
# ============================================================================

def validate_appeal_input(data: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Validate the appeal request payload.

    Args:
        data: The JSON payload from the request.

    Returns:
        A tuple (is_valid, error_message). If is_valid is True, error_message is empty.
    """
    if not isinstance(data, dict):
        return False, "Request body must be a JSON object."

    # Check required fields
    required_fields = ["content_id", "creator_id", "reasoning"]
    for field in required_fields:
        if field not in data:
            return False, f"Missing required field: '{field}'."

    content_id = data.get("content_id")
    creator_id = data.get("creator_id")
    reasoning = data.get("reasoning")
    evidence = data.get("evidence")

    # Validate content_id
    if not isinstance(content_id, str):
        return False, "Field 'content_id' must be a string."

    if len(content_id.strip()) == 0:
        return False, "Field 'content_id' cannot be empty."

    # Validate creator_id
    if not isinstance(creator_id, str):
        return False, "Field 'creator_id' must be a string."

    if len(creator_id.strip()) == 0:
        return False, "Field 'creator_id' cannot be empty."

    # Validate reasoning (50-1000 characters)
    if not isinstance(reasoning, str):
        return False, "Field 'reasoning' must be a string."

    reasoning_length = len(reasoning.strip())
    if reasoning_length < 50:
        return False, "Field 'reasoning' must be at least 50 characters long."

    if reasoning_length > 1000:
        return False, "Field 'reasoning' must not exceed 1000 characters."

    # Validate evidence (optional, but if present should be valid URL)
    if evidence is not None:
        if not isinstance(evidence, str):
            return False, "Field 'evidence' must be a string."

        evidence_str = evidence.strip()
        if len(evidence_str) > 0:
            # Basic URL validation
            try:
                result = urlparse(evidence_str)
                if not all([result.scheme, result.netloc]):
                    return False, "Field 'evidence' must be a valid URL."
            except Exception:
                return False, "Field 'evidence' must be a valid URL."

    return True, ""


def is_valid_url(url: str) -> bool:
    """
    Check if a URL is valid.

    Args:
        url: URL string to validate.

    Returns:
        True if valid, False otherwise.
    """
    try:
        result = urlparse(url)
        return all([result.scheme, result.netloc])
    except Exception:
        return False


