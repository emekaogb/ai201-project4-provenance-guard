"""
Label generation for Provenance Guard transparency labels and appeals processing.

This module provides:
1. generate_label() - Create transparency labels based on classification and confidence
2. generate_appeal_endpoint() - Flask endpoint handler for /api/appeals/submit
"""

import uuid
import logging
from datetime import datetime
from typing import Dict, Any, Tuple
from urllib.parse import urlparse

from flask import request, jsonify
from src.audit_log import get_submission_by_id, log_appeal

# Configure logging
logger = logging.getLogger(__name__)


# ============================================================================
# Label Generation
# ============================================================================

def generate_label(classification: str, confidence: float) -> Dict[str, str]:
    """
    Generate a transparency label based on classification and confidence score.

    Takes a classification result ("human", "ai", or "uncertain") and a confidence
    score (0-1), and returns a dictionary with the appropriate transparency label
    variant including title, description, and confidence level.

    Args:
        classification: One of "human", "ai", or "uncertain"
        confidence: Confidence score between 0 and 1

    Returns:
        Dictionary with keys:
        - "title": Short title (e.g., "✓ Likely written by a human")
        - "description": Full description text matching planning.md exactly
        - "confidence_level": One of "high", "medium", or "low"

    Examples:
        >>> label = generate_label("human", 0.75)
        >>> label["title"]
        '✓ Likely written by a human'
        >>> label["confidence_level"]
        'high'

        >>> label = generate_label("ai", 0.85)
        >>> label["title"]
        '⚠ Likely generated by AI'

        >>> label = generate_label("uncertain", 0.55)
        >>> label["title"]
        '? We\'re unsure about the authorship'
        >>> label["confidence_level"]
        'low'

    Logic:
        - IF classification == "human" AND confidence > 0.6:
          Return the "High-Confidence Human" variant with confidence_level="high"
        - IF classification == "ai" AND confidence > 0.6:
          Return the "High-Confidence AI" variant with confidence_level="high"
        - ELSE (classification == "uncertain" OR confidence <= 0.6):
          Return the "Uncertain" variant with confidence_level="low" or "medium"
    """
    # Determine confidence level
    if confidence > 0.7:
        confidence_level = "high"
    elif confidence > 0.5:
        confidence_level = "medium"
    else:
        confidence_level = "low"

    # High-Confidence Human
    if classification == "human" and confidence > 0.6:
        return {
            "title": "✓ Likely written by a human",
            "description": (
                "We're highly confident this content was written by a person.\n\n"
                "How we detected this:\n"
                "The writing shows natural variation in sentence structure and vocabulary "
                "choices that are typical of human authorship. The text uses diverse "
                "sentence lengths and includes natural discourse patterns."
            ),
            "confidence_level": "high",
        }

    # High-Confidence AI
    elif classification == "ai" and confidence > 0.6:
        return {
            "title": "⚠ Likely generated by AI",
            "description": (
                "We're highly confident this content was generated by an AI system, "
                "not written by a human.\n\n"
                "How we detected this:\n"
                "The text shows patterns of predictability and structural consistency "
                "that are typical of AI-generated content. Sentences have uniform length "
                "and structure, with formal discourse markers appearing systematically."
            ),
            "confidence_level": "high",
        }

    # Uncertain (fallback for classification=="uncertain" OR confidence <= 0.6)
    else:
        return {
            "title": "? We're unsure about the authorship",
            "description": (
                "Our analysis suggests this content has characteristics of both human "
                "and AI writing.\n\n"
                "This might mean:\n"
                "• The content is a blend of human and AI (e.g., AI draft revised by a human)\n"
                "• The writing style is unusual for our detection system\n"
                "• The author writes in a very formal or mechanical way\n"
                "• The text is too short for reliable analysis\n\n"
                "If you're the creator and this is your original work, you can appeal "
                "this classification."
            ),
            "confidence_level": confidence_level,
        }


