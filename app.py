@app.route("/api/log", methods=["GET"])
def get_audit_log():
    """
    Retrieve audit log entries.

    Query parameters:
    - limit: Maximum number of entries to return (default: 10, max: 100)
    - offset: Number of entries to skip from the end (default: 0)

    Returns:
    {
        "entries": [
            {
                "content_id": "...",
                "creator_id": "...",
                "timestamp": "...",
                "attribution": "...",
                "confidence": 0.85,
                "llm_score": 0.75,
                "status": "..."
            },
            ...
        ],
        "count": 10
    }
    """
    try:
        limit = request.args.get("limit", 10, type=int)
        offset = request.args.get("offset", 0, type=int)

        # Clamp limit to reasonable values
        limit = max(1, min(100, limit))
        offset = max(0, offset)

        entries = get_log(limit=limit, offset=offset)

        return jsonify({
            "entries": entries,
            "count": len(entries)
        }), 200

    except Exception as e:
        logger.error(f"Error retrieving audit log: {str(e)}")
        return jsonify({"error": "Error retrieving audit log."}), 500


@app.route("/api/log/text", methods=["GET"])
def get_audit_log_text():
    """
    Retrieve audit log entries as formatted text.

    Query parameters:
    - limit: Maximum number of entries to return (default: 10, max: 100)

    Returns:
    Plain text formatted log entries.
    """
    try:
        limit = request.args.get("limit", 10, type=int)
        limit = max(1, min(100, limit))

        entries = get_log(limit=limit, offset=0)

        # Format as text
        text_output = "=== Provenance Guard Audit Log ===\n\n"
        for entry in entries:
            text_output += f"[{entry.get('content_id', 'N/A')[:8]}...] {entry.get('timestamp', 'N/A')}\n"
            text_output += f"  Creator: {entry.get('creator_id', 'N/A')}\n"
            text_output += f"  Attribution: {entry.get('attribution', 'N/A').upper()} ({entry.get('confidence', 0):.1%} confidence)\n"
            text_output += f"  Signal 1 (Perplexity): {entry.get('llm_score', 'N/A')}\n"
            text_output += f"  Status: {entry.get('status', 'N/A')}\n"
            text_output += "\n"

        return text_output, 200, {"Content-Type": "text/plain"}

    except Exception as e:
        logger.error(f"Error generating audit log text: {str(e)}")
        return "Error retrieving audit log.", 500, {"Content-Type": "text/plain"}


