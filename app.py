def validate_submission_input(data: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Validate the submission request payload.

    Args:
        data: The JSON payload from the request.

    Returns:
        A tuple (is_valid, error_message). If is_valid is True, error_message is empty.
    """
    if not isinstance(data, dict):
        return False, "Request body must be a JSON object."

    # Check required fields
    if "text" not in data:
        return False, "Missing required field: 'text'."

    if "creator_id" not in data:
        return False, "Missing required field: 'creator_id'."

    text = data.get("text")
    creator_id = data.get("creator_id")

    # Validate text
    if not isinstance(text, str):
        return False, "Field 'text' must be a string."

    text = text.strip()
    if len(text) == 0:
        return False, "Field 'text' cannot be empty."

    if len(text) < 5:
        return False, "Field 'text' must be at least 5 characters long."

    if len(text) > 5000:
        return False, "Field 'text' exceeds maximum length of 5000 characters."

    # Validate creator_id
    if not isinstance(creator_id, str):
        return False, "Field 'creator_id' must be a string."

    if len(creator_id.strip()) == 0:
        return False, "Field 'creator_id' cannot be empty."

    return True, ""


